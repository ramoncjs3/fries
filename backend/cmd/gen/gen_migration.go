package main

import (
	"fmt"
	"sort"
	"strings"
)

// genMigration 由模块定义产出建表迁移的 SQL（不含文件名里的编号，那个由调用方拼）。
//
// ⚠️ **产出的表一开始就是多租户的**（MULTI-TENANCY.md §14、§11.1）：
//   - tenant_id uuid NOT NULL REFERENCES tenants (id)
//   - 唯一索引一律 (tenant_id, …) 打头、软删除用部分索引 WHERE deleted_at IS NULL
//   - 供复合外键引用的 uk_<表>_tenant_id (tenant_id, id)
//
// 这份产出会被 lint-sql 的 B1/B2 复查 —— 但那是发现，不是预防，所以这里就得写对。
func genMigration(def *ModuleDef) string {
	table := pluralize(def.Key)
	var b strings.Builder

	fmt.Fprintf(&b, "-- %s（%s）。由 fries-gen 生成的建表迁移。\n", def.Name, def.Key)
	b.WriteString("-- Code generated by fries-gen. DO NOT EDIT.\n\n")
	b.WriteString("-- +goose Up\n\n")
	b.WriteString("SET LOCAL lock_timeout = '5s';\n")
	b.WriteString("SET LOCAL statement_timeout = '60s';\n\n")

	// 建表：id → tenant_id → 业务字段 → 标准尾列。
	fmt.Fprintf(&b, "CREATE TABLE %s (\n", table)
	b.WriteString("    id         uuid        PRIMARY KEY,\n")
	b.WriteString("    tenant_id  uuid        NOT NULL REFERENCES tenants (id),\n")
	for _, f := range def.Fields {
		b.WriteString("    " + columnLine(f) + "\n")
	}
	b.WriteString("\n")
	b.WriteString("    created_at timestamptz NOT NULL DEFAULT now(),\n")
	b.WriteString("    updated_at timestamptz NOT NULL DEFAULT now(),\n")
	b.WriteString("    deleted_at timestamptz,\n")
	b.WriteString("    created_by uuid,\n")
	b.WriteString("    version    integer     NOT NULL DEFAULT 0\n")
	b.WriteString(");\n\n")

	// 复合外键引用锚点：(tenant_id, id) 唯一。别的租户表要外键指过来时用它（§2.2.1）。
	fmt.Fprintf(&b, "CREATE UNIQUE INDEX uk_%s_tenant_id ON %s (tenant_id, id);\n", table, table)

	// 唯一字段：部分唯一索引，tenant_id 打头（跨租户不串味 + 软删除不占位）。
	for _, f := range def.Fields {
		if f.Unique {
			fmt.Fprintf(&b, "CREATE UNIQUE INDEX uk_%s_%s ON %s (tenant_id, %s) WHERE deleted_at IS NULL;\n",
				table, f.Name, table, f.Name)
		}
	}
	// 可筛选字段：普通索引，tenant_id 打头。
	for _, f := range def.Fields {
		if f.Filterable && !f.Unique {
			fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s ON %s (tenant_id, %s);\n",
				table, f.Name, table, f.Name)
		}
	}
	// 可搜索字段：pg_trgm GIN 索引（模糊匹配靠它，pg_trgm 扩展在 00001 建过）。
	for _, f := range def.Fields {
		if f.Searchable {
			fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s_trgm ON %s USING gin (%s gin_trgm_ops);\n",
				table, f.Name, table, f.Name)
		}
	}
	// ref 字段：**复合外键 (tenant_id, <字段>) → <目标表>(tenant_id, id)**，防跨租户引用（§2.2.1）——
	// 光 REFERENCES <目标>(id) 挡不住「引用别家租户的行」，必须把 tenant_id 一起锚进去。
	// 外加一个查询用索引。目标表的 (tenant_id, id) 唯一锚点由目标模块的迁移建（uk_<目标>_tenant_id）。
	for _, f := range def.Fields {
		if f.Type == typeRef {
			target := pluralize(f.Ref)
			fmt.Fprintf(&b, "ALTER TABLE %s ADD CONSTRAINT fk_%s_%s\n    FOREIGN KEY (tenant_id, %s) REFERENCES %s (tenant_id, id);\n",
				table, table, f.Name, f.Name, target)
			if !f.Filterable && !f.Unique {
				fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s ON %s (tenant_id, %s);\n",
					table, f.Name, table, f.Name)
			}
		}
	}

	// updated_at 触发器（函数在 00001 定义）。
	fmt.Fprintf(&b, "\nCREATE TRIGGER trg_%s_updated_at\n", table)
	fmt.Fprintf(&b, "    BEFORE UPDATE ON %s\n", table)
	b.WriteString("    FOR EACH ROW EXECUTE FUNCTION set_updated_at();\n\n")

	fmt.Fprintf(&b, "-- +goose Down\nDROP TABLE %s;\n", table)
	return b.String()
}

// columnLine 产出一个业务字段的列定义。
func columnLine(f Field) string {
	col := fmt.Sprintf("%-10s %s", f.Name, pgType(f))
	if f.Required {
		col += " NOT NULL"
	}
	if d := pgDefault(f); d != "" {
		col += " DEFAULT " + d
	}
	if f.Type == typeEnum {
		col += " " + enumCheck(f)
	}
	return col + ","
}

// pgType 把字段类型映射成 PG 列类型（DECISIONS.md §10.2）。
func pgType(f Field) string {
	switch f.Type {
	case typeString:
		return fmt.Sprintf("varchar(%d)", f.Max)
	case typeText:
		return "text"
	case typeInt:
		return "integer"
	case typeDecimal:
		return fmt.Sprintf("numeric(%d, %d)", f.Precision[0], f.Precision[1])
	case typeBool:
		return "boolean"
	case typeEnum:
		return "varchar(32)"
	case typeDate:
		return "date"
	case typeTimestamp:
		return "timestamptz"
	case typeRef:
		return "uuid"
	default:
		// 到不了这里：校验期已挡下未知类型（fieldTypes）。兜底给 text。
		return "text"
	}
}

// pgDefault 产出列的 DEFAULT 片段（没有默认值返回空串）。
func pgDefault(f Field) string {
	if f.Default == "" {
		return ""
	}
	switch f.Type {
	case typeInt, typeDecimal, typeBool:
		return f.Default // 数字 / 布尔字面量直接放
	default:
		return "'" + strings.ReplaceAll(f.Default, "'", "''") + "'" // 其余按字符串加引号
	}
}

// enumCheck 产出 enum 字段的 CHECK 约束：col IN ('a', 'b')。code 排序，产出稳定。
func enumCheck(f Field) string {
	codes := make([]string, 0, len(f.Values))
	for code := range f.Values {
		codes = append(codes, "'"+code+"'")
	}
	sort.Strings(codes)
	return fmt.Sprintf("CHECK (%s IN (%s))", f.Name, strings.Join(codes, ", "))
}

// pluralize 把模块 key 变成表名。规则简单，覆盖常见英文复数；不规则的自己在 YAML 里避开。
func pluralize(key string) string {
	switch {
	case strings.HasSuffix(key, "y") && !endsInVowelY(key):
		return key[:len(key)-1] + "ies"
	case strings.HasSuffix(key, "s"), strings.HasSuffix(key, "x"),
		strings.HasSuffix(key, "z"), strings.HasSuffix(key, "ch"),
		strings.HasSuffix(key, "sh"):
		return key + "es"
	default:
		return key + "s"
	}
}

// endsInVowelY 判断 y 前面是不是元音（day→days，而 category→categories）。
func endsInVowelY(key string) bool {
	if len(key) < 2 {
		return false
	}
	return strings.ContainsRune("aeiou", rune(key[len(key)-2]))
}
