package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// gen_alter.go 是「增量改字段」（DECISIONS.md §10.4）：表已经建过了，再跑 make gen-module，
// 生成器比对 YAML 和现有列，给**新增的字段**产一条 ALTER 增量迁移（建表迁移是 write-once，不动）。
//
// ⚠️ **迁移安全**：给一张**已有数据**的表加 `NOT NULL` 列，现有行没值会违反约束、迁移当场失败。
// 所以新增字段要么可选，要么必填但给了 default（现有行拿默认值填上）；新增的必填外键没有合理默认，
// 直接拒。删列/改类型这类破坏性变更不自动做（风险太大），只处理「加字段」这一最常见的安全场景。

var (
	// 建表里一行业务列：缩进 + 标识符 + 空白（后面跟类型）。约束/索引不在 CREATE TABLE 里（走 ALTER/单独语句）。
	rxColLine = regexp.MustCompile(`(?m)^\s+([a-z][a-z0-9_]*)\s`)
)

// existingColumns 扫迁移目录，收集某张表现在有哪些列（建表里的 + 后续 ALTER ADD COLUMN 的）。
func existingColumns(migDir, table string) (map[string]bool, error) {
	cols := map[string]bool{}
	entries, err := os.ReadDir(migDir)
	if err != nil {
		return nil, fmt.Errorf("读迁移目录 %s: %w", migDir, err)
	}
	rxAdd := regexp.MustCompile(`ALTER TABLE ` + regexp.QuoteMeta(table) + ` ADD COLUMN ([a-z][a-z0-9_]*)`)
	createHead := "CREATE TABLE " + table + " ("
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(migDir, e.Name()))
		if err != nil {
			return nil, err
		}
		s := string(raw)
		// 建表块里的列。**块尾用 `\n);`**（建表的收尾 `);` 单独一行），不能用裸 `);` ——
		// 某列 default 值里含 `);`（如 `DEFAULT 'a);b'`）会让块被提前截断、其后的列全漏读，
		// 判成「新字段」→ 再产一遍 ADD COLUMN → 迁移报 column already exists。
		if i := strings.Index(s, createHead); i >= 0 {
			block := s[i:]
			if j := strings.Index(block, "\n);"); j >= 0 {
				block = block[:j]
			}
			for _, m := range rxColLine.FindAllStringSubmatch(block, -1) {
				cols[m[1]] = true
			}
		}
		// 后续 ALTER 加的列。
		for _, m := range rxAdd.FindAllStringSubmatch(s, -1) {
			cols[m[1]] = true
		}
	}
	return cols, nil
}

// newFields 返回 YAML 里有、但表里还没有的字段（按 def.Fields 顺序）。
func newFields(def *ModuleDef, existing map[string]bool) []Field {
	var out []Field
	for _, f := range def.Fields {
		if !existing[f.Name] {
			out = append(out, f)
		}
	}
	return out
}

// genAlterMigration 给一批新增字段产 ALTER 增量迁移。新增的必填列没有 default（或必填外键）会报错。
func genAlterMigration(def *ModuleDef, fields []Field) (string, error) {
	table := pluralize(def.Key)
	for _, f := range fields {
		switch {
		case f.Required && f.Type == typeRef:
			return "", fmt.Errorf("新增字段 %s 是必填外键 —— 给有数据的表加 NOT NULL 外键没有合理默认值。"+
				"设成可选（required: false），或先把数据补齐再单独改必填", f.Name)
		case f.Required && pgDefault(f) == "":
			return "", fmt.Errorf("新增字段 %s 是必填但没给 default —— 给有数据的表加 NOT NULL 列，"+
				"现有行会违反约束。给它一个 default，或设成可选（required: false）", f.Name)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "-- %s（%s）增量：新增字段 %s。由 fries-gen 生成。\n", def.Name, def.Key, fieldNames(fields))
	b.WriteString("-- Code generated by fries-gen. DO NOT EDIT.\n\n")
	b.WriteString("-- +goose Up\n\n")
	b.WriteString("SET LOCAL lock_timeout = '5s';\n")
	b.WriteString("SET LOCAL statement_timeout = '60s';\n\n")

	for _, f := range fields {
		fmt.Fprintf(&b, "ALTER TABLE %s ADD COLUMN %s %s;\n", table, f.Name, columnDef(f))
	}
	// 索引：唯一 / 可筛选 / 可搜索，规则和建表一致（tenant_id 打头）。
	for _, f := range fields {
		switch {
		case f.Unique:
			fmt.Fprintf(&b, "CREATE UNIQUE INDEX uk_%s_%s ON %s (tenant_id, %s) WHERE deleted_at IS NULL;\n",
				table, f.Name, table, f.Name)
		case f.Filterable:
			fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s ON %s (tenant_id, %s);\n", table, f.Name, table, f.Name)
		}
		if f.Searchable {
			fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s_trgm ON %s USING gin (%s gin_trgm_ops);\n",
				table, f.Name, table, f.Name)
		}
		if f.Type == typeRef {
			target := pluralize(f.Ref)
			fmt.Fprintf(&b, "ALTER TABLE %s ADD CONSTRAINT fk_%s_%s\n    FOREIGN KEY (tenant_id, %s) REFERENCES %s (tenant_id, id);\n",
				table, table, f.Name, f.Name, target)
			if !f.Filterable && !f.Unique {
				fmt.Fprintf(&b, "CREATE INDEX idx_%s_%s ON %s (tenant_id, %s);\n", table, f.Name, table, f.Name)
			}
		}
	}

	b.WriteString("\n-- +goose Down\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "ALTER TABLE %s DROP COLUMN %s;\n", table, f.Name)
	}
	return b.String(), nil
}

// columnDef 是一列的定义部分（类型 + NOT NULL + DEFAULT + enum CHECK），ALTER ADD COLUMN 用。
func columnDef(f Field) string {
	def := pgType(f)
	if f.Required {
		def += " NOT NULL"
	}
	if d := pgDefault(f); d != "" {
		def += " DEFAULT " + d
	}
	if f.Type == typeEnum {
		def += " " + enumCheck(f)
	}
	return def
}

func fieldNames(fields []Field) string {
	names := make([]string, len(fields))
	for i, f := range fields {
		names[i] = f.Name
	}
	return strings.Join(names, ", ")
}
