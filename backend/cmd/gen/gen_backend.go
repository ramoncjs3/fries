package main

import (
	"fmt"
	"strings"
)

// seedHeader 是**种子文件**的头（§10.3）：只在文件不存在时生成，之后归人/AI 所有，重生成不覆盖。
const seedHeader = "// Generated by fries-gen as a starting point.\n" +
	"// Safe to edit — regeneration will not overwrite.\n\n"

// actionNames 是标准动作的中文名。
var actionNames = map[string]string{
	actList: "查询", actRead: "查看", actCreate: "新增",
	actUpdate: "编辑", actDelete: "删除", actExport: "导出",
}

// actionKeyExpr 把动作 key 变成 perm 包里的表达式：标准四个用常量，其余用字面量。
func actionKeyExpr(a string) string {
	switch a {
	case actList:
		return "perm.ActionList"
	case actCreate:
		return "perm.ActionCreate"
	case actUpdate:
		return "perm.ActionUpdate"
	case actDelete:
		return "perm.ActionDelete"
	default:
		return fmt.Sprintf("%q", a) // read / export 没有常量，用字面量
	}
}

// genPermModule 产出 internal/perm/modules/<key>.go —— 模块的权限点声明（种子文件）。
func genPermModule(def *ModuleDef) string {
	entity := pascal(def.Key)
	var b strings.Builder
	b.WriteString(seedHeader)
	b.WriteString("package modules\n\n")
	b.WriteString("import \"github.com/ramoncjs3/fries/internal/perm\"\n\n")
	fmt.Fprintf(&b, "// %s 是%s模块的权限声明。\n", entity, def.Name)
	fmt.Fprintf(&b, "var %s = perm.Register(perm.Module{\n", entity)
	fmt.Fprintf(&b, "\tKey:    %q,\n", def.Key)
	fmt.Fprintf(&b, "\tName:   %q,\n", def.Name)
	b.WriteString("\tRealm:  perm.RealmTenant,\n")
	fmt.Fprintf(&b, "\tScoped: %v,\n", def.Scoped)
	fmt.Fprintf(&b, "\tMenu:   perm.Menu{Path: %q, Icon: %q, ShowIf: perm.ActionList, Order: %d},\n",
		def.Menu.Path, def.Menu.Icon, def.Menu.menuOrder())
	b.WriteString("\tActions: []perm.Action{\n")
	for _, a := range def.Actions {
		fmt.Fprintf(&b, "\t\t{Key: %s, Name: %q},\n", actionKeyExpr(a), actionNames[a])
	}
	b.WriteString("\t},\n})\n")
	return b.String()
}

// genErrors 产出 internal/service/<key>/errors.go —— 模块专属错误码（种子文件）。
//
// 目前只产唯一字段的「已被占用」冲突码（uk_<表>_<字段> 违反时翻译成人话，
// 不然用户看到的是 DB 的 23505）。别的业务错误码由人手补。
func genErrors(def *ModuleDef) string {
	table := pluralize(def.Key)
	var uniques []Field
	for _, f := range def.Fields {
		if f.Unique {
			uniques = append(uniques, f)
		}
	}

	var b strings.Builder
	b.WriteString(seedHeader)
	fmt.Fprintf(&b, "package %s\n\n", def.Key)

	if len(uniques) == 0 {
		fmt.Fprintf(&b, "// %s 暂时没有唯一字段，也就没有模块专属的冲突错误码。\n", def.Name)
		b.WriteString("// 有业务错误要报时，照 role/service 的 errors.go 用 errs.Define 补。\n")
		return b.String()
	}

	b.WriteString("import (\n\t\"net/http\"\n\n\t\"github.com/ramoncjs3/fries/internal/errs\"\n)\n\n")
	b.WriteString("// 模块专属错误码。前缀是模块 key（DECISIONS.md §4.5）。\n")
	b.WriteString("var (\n")
	for _, f := range uniques {
		// 索引名和迁移里一致（uk_<表>_<字段>），service 层靠它把唯一冲突翻译成人话。
		fmt.Fprintf(&b, "\t// 唯一索引 uk_%s_%s 冲突时用。\n", table, f.Name)
		fmt.Fprintf(&b, "\tErr%sTaken = errs.Define(%q, http.StatusConflict,\n\t\t%q)\n",
			pascal(f.Name), def.Key+"."+f.Name+"_taken", f.Label+"已被占用")
	}
	b.WriteString(")\n")
	return b.String()
}
