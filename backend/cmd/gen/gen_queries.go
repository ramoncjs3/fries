package main

import (
	"fmt"
	"strings"
)

// genQueries 由模块定义产出 db/queries/<key>.sql 的 sqlc 查询（CRUD）。
//
// ⚠️ **每条查询都带 tenant_id**（sqlc.arg('tenant_id')）——「按 id 查一行」也不例外
// （BOLA，MULTI-TENANCY.md §11.1）。带了 tenant_id 的查询会被生成器分流到 ForTenant 句柄上，
// 租户由句柄注入，业务代码碰不到那个字段。软删除走 deleted_at，改/删带乐观锁 version。
func genQueries(def *ModuleDef) string {
	table := pluralize(def.Key)
	entity := pascal(def.Key)
	entities := pascal(table)

	// tenant_id 相关片段一律从 tenantIDCol 常量拼，避免在 SQL 文本里散落字面量。
	tenantEq := fmt.Sprintf("%s = sqlc.arg('%s')", tenantIDCol, tenantIDCol)
	tenantArg := fmt.Sprintf("sqlc.arg('%s')", tenantIDCol)

	var b strings.Builder
	fmt.Fprintf(&b, "-- %s（%s）的 CRUD 查询。由 fries-gen 生成。\n", def.Name, def.Key)
	b.WriteString("-- Code generated by fries-gen. DO NOT EDIT.\n\n")

	// 有要反查名字的 ref → List/Get 用别名 t + sqlc.embed(t) + LEFT JOIN，把目标名字作为
	// <字段>_label 一并查出来（列表 cell / 详情读态直接显示名字，不用前端逐条反查）。租户锚在
	// JOIN 条件上（r.tenant_id = t.tenant_id），对齐 user 模块的做法，租户检查器认这个。
	// 增删改（RETURNING *）不动，仍用不带别名的 tenantEq。
	labelRefs := refLabelFields(def)
	alias, dot := "", ""
	if len(labelRefs) > 0 {
		alias, dot = " t", "t."
	}
	tenantEqRead := fmt.Sprintf("%s%s = sqlc.arg('%s')", dot, tenantIDCol, tenantIDCol)
	whereRead := "WHERE " + tenantEqRead + "\n  AND " + dot + "deleted_at IS NULL" +
		searchClause(def, dot) + filterClause(def, dot)
	selectRead, joins := "*", ""
	if len(labelRefs) > 0 {
		selectRead = "sqlc.embed(t)" + labelSelectCols(def, labelRefs)
		joins = labelJoins(def, labelRefs)
	}

	// List
	fmt.Fprintf(&b, "-- name: List%s :many\nSELECT %s\nFROM %s%s%s\n%s\nORDER BY %screated_at DESC\nLIMIT sqlc.arg('limit') OFFSET sqlc.arg('offset');\n\n",
		entities, selectRead, table, alias, joins, whereRead, dot)

	// Count（不需要 JOIN；别名只为让 where 里的 t. 有得解析）
	fmt.Fprintf(&b, "-- name: Count%s :one\nSELECT count(*)\nFROM %s%s\n%s;\n\n",
		entities, table, alias, whereRead)

	// Get by id（也要带 tenant_id —— 改 URL 里的 id 只会查到 0 行）
	fmt.Fprintf(&b, "-- name: Get%s :one\nSELECT %s\nFROM %s%s%s\nWHERE %s AND %sid = sqlc.arg('id') AND %sdeleted_at IS NULL;\n\n",
		entity, selectRead, table, alias, joins, tenantEqRead, dot, dot)

	// Create
	cols := make([]string, 0, len(def.Fields)+3)
	vals := make([]string, 0, len(def.Fields)+3)
	cols = append(cols, tenantIDCol, "id")
	vals = append(vals, tenantArg, "sqlc.arg('id')")
	for _, f := range def.Fields {
		cols = append(cols, f.Name)
		vals = append(vals, argFor(f))
	}
	cols = append(cols, "created_by")
	vals = append(vals, "sqlc.narg('created_by')")
	fmt.Fprintf(&b, "-- name: Create%s :one\nINSERT INTO %s (%s)\nVALUES (%s)\nRETURNING *;\n\n",
		entity, table, strings.Join(cols, ", "), strings.Join(vals, ", "))

	// Update（乐观锁：带 version，命中 0 行说明版本过期）
	sets := make([]string, 0, len(def.Fields)+1)
	for _, f := range def.Fields {
		sets = append(sets, fmt.Sprintf("%s = %s", f.Name, argFor(f)))
	}
	sets = append(sets, "version = version + 1")
	fmt.Fprintf(&b, "-- name: Update%s :one\nUPDATE %s\nSET %s\nWHERE %s\n  AND id = sqlc.arg('id')\n  AND version = sqlc.arg('version')\n  AND deleted_at IS NULL\nRETURNING *;\n\n",
		entity, table, strings.Join(sets, ",\n    "), tenantEq)

	// SoftDelete（软删除 + 乐观锁）
	fmt.Fprintf(&b, "-- name: SoftDelete%s :execrows\nUPDATE %s\nSET deleted_at = now(), version = version + 1\nWHERE %s\n  AND id = sqlc.arg('id')\n  AND version = sqlc.arg('version')\n  AND deleted_at IS NULL;\n",
		entity, table, tenantEq)

	return b.String()
}

// searchClause 产出关键字模糊搜索条件（searchable 字段做 ILIKE）。没有可搜字段就返回空串。
// dot 是列前缀（有 JOIN 时为 "t."，否则空）—— 有 JOIN 时列名要带别名，不然和被 JOIN 的表撞名歧义。
func searchClause(def *ModuleDef, dot string) string {
	likes := make([]string, 0, len(def.Fields))
	for _, f := range def.Fields {
		if f.Searchable {
			likes = append(likes, fmt.Sprintf("%s%s ILIKE sqlc.narg('keyword')", dot, f.Name))
		}
	}
	if len(likes) == 0 {
		return ""
	}
	return "\n  AND (sqlc.narg('keyword')::varchar IS NULL OR " + strings.Join(likes, " OR ") + ")"
}

// filterClause 产出可筛选字段的等值条件（filterable 字段，narg 为空则不筛）。dot 同 searchClause。
func filterClause(def *ModuleDef, dot string) string {
	var b strings.Builder
	for _, f := range def.Fields {
		if f.Filterable {
			fmt.Fprintf(&b, "\n  AND (sqlc.narg('%s')::%s IS NULL OR %s%s = sqlc.narg('%s'))",
				f.Name, sqlcCastType(f), dot, f.Name, f.Name)
		}
	}
	return b.String()
}

// argFor 产出一个字段在 INSERT/UPDATE 里的参数：必填用 arg，可空用 narg。
func argFor(f Field) string {
	if f.Required {
		return fmt.Sprintf("sqlc.arg('%s')", f.Name)
	}
	return fmt.Sprintf("sqlc.narg('%s')", f.Name)
}

// sqlcCastType 是 narg 条件里 `::类型` 用的 PG 类型（sqlc 靠它推断参数类型）。
func sqlcCastType(f Field) string {
	switch f.Type {
	case typeInt:
		return "integer"
	case typeDecimal:
		return "numeric"
	case typeBool:
		return "boolean"
	case typeDate:
		return "date"
	case typeTimestamp:
		return "timestamptz"
	default:
		return "varchar"
	}
}

// initialisms 是要整段大写的缩略词，**必须和 sqlc 的产出对齐** —— 否则生成的 service/handler
// 引用的字段名（如 SupplierID）和 sqlc 产的对不上，4e 编译就炸，而且 Id 这种还过不了 golint。
// sqlc 内置把 id 当缩略词（现有 ParentID/UserID 就是），ref 字段 <x>_id 全靠它。
// ⚠️ 只列确认 sqlc 也这么处理的：ip/http 这个项目是靠 sqlc.yaml 的 rename 单独配的，别往这加。
var initialisms = map[string]bool{"id": true}

// pascal 把 snake_case 转成 PascalCase（supplier → Supplier，service_account → ServiceAccount，
// supplier_id → SupplierID）。缩略词整段大写（对齐 sqlc）。
func pascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		switch {
		case p == "":
		case initialisms[p]:
			parts[i] = strings.ToUpper(p)
		default:
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}
